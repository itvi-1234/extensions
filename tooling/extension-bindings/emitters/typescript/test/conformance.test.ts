import assert from "node:assert/strict";
import { rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import * as prettier from "prettier";

import { loadModel } from "../src/model.js";
import { buildPlan } from "../src/plan.js";
import { emitPackage, FORMAT_OPTIONS } from "../src/source.js";
import { apiSurface, verifyPackage } from "../src/verification.js";
import {
  CASES,
  buildCase,
  developmentTarget,
  modelPath,
  planFor,
  runTsc,
  snapshot,
  temporaryDirectory,
  writeConformance,
} from "./support.js";

for (const name of CASES) {
  test(`${name}: emits, verifies, and compiles under strict tsc`, async () => {
    const workspace = temporaryDirectory();
    try {
      const built = await buildCase(name, workspace);
      verifyPackage(built.plan, built.directory, built.model);
      writeConformance(built);
      const compiled = runTsc(built.directory, true);
      assert.equal(compiled.status, 0, compiled.output);
      assert.ok(apiSurface(built.directory).length > 0);
    } finally {
      rmSync(workspace, { recursive: true, force: true });
    }
  });

  test(`${name}: three independent emissions are byte-identical and Prettier-stable`, async () => {
    const model = loadModel(modelPath(name));
    const runs: Record<string, string>[] = [];
    const workspace = temporaryDirectory();
    try {
      for (let run = 0; run < 3; run += 1) {
        const plan = planFor(model, name);
        const directory = join(workspace, `run-${run}`);
        await emitPackage(plan, model, directory);
        runs.push(snapshot(directory));
      }
      assert.deepEqual(runs[1], runs[0]);
      assert.deepEqual(runs[2], runs[0]);
      for (const [path, content] of Object.entries(runs[0]!)) {
        if (path.endsWith(".ts")) {
          assert.ok(
            await prettier.check(content, { ...FORMAT_OPTIONS, filepath: path }),
            `${path} is not Prettier-formatted`,
          );
          assert.ok(
            content.startsWith(
              "// Code generated by runtimeconditions-binding-emitter-typescript 0.1.0 from model ",
            ),
          );
          assert.ok(content.split("\n")[0]!.endsWith("DO NOT EDIT."));
        }
      }
    } finally {
      rmSync(workspace, { recursive: true, force: true });
    }
  });
}

