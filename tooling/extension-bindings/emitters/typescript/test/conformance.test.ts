test("a JSON-valued root field maps to the recursive JSONValue alias and compiles", async () => {
  const model = loadModel(modelPath("01-owned-kind-interface"));
  const shape = model["schemas"][0].projection.properties[1].shape;
  delete shape.scalar;
  shape.kind = "any";
  model["scopes"][0].projection.properties[1].shape = structuredClone(shape);
  const plan = buildPlan(model, {
    ...developmentTarget(),
    rootExtension: model["rootExtension"].id,
  });
  assert.equal(plan.usesJsonValue, true);
  const workspace = temporaryDirectory();
  try {
    const directory = join(workspace, "package");
    await emitPackage(plan, model, directory);
    verifyPackage(plan, directory, model);
    const built = { directory, model, plan };
    writeConformance(built);
    const compiled = runTsc(directory, true);
    assert.equal(compiled.status, 0, compiled.output);
  } finally {
    rmSync(workspace, { recursive: true, force: true });
  }
});

test("generated types reject values the model does not allow", async () => {
  const workspace = temporaryDirectory();
  try {
    const built = await buildCase("10-scoped-domains-collisions", workspace);
    const probes: [string, string][] = [
      ["wrong enum value", 'const _x = new b.HttpMode({ value: "streaming" });'],
      ["wrong scalar type", "const _x = new b.BaseUrl({ value: 1 });"],
      ["missing required field", "const _x = new b.BaseUrl({});"],
      ["non-field argument to a declaration", 'const _x = b.service({ value: "x" });'],
    ];
    for (const [description, line] of probes) {
      writeFileSync(
        join(built.directory, "src/_probe.ts"),
        `import * as b from "./bindings.js";\nexport function probe(): void {\n  ${line}\n  void _x;\n}\n`,
      );
      const compiled = runTsc(built.directory, true);
      assert.notEqual(compiled.status, 0, `${description} should not compile`);
    }
    rmSync(join(built.directory, "src/_probe.ts"));
    writeFileSync(
      join(built.directory, "src/_probe.ts"),
      'import * as b from "./bindings.js";\nexport const ok = b.service(new b.BaseUrl({ value: "x" }), new b.HttpMode({ value: b.HttpModeValue.Direct }));\n',
    );
    assert.equal(runTsc(built.directory, true).status, 0);
  } finally {
    rmSync(workspace, { recursive: true, force: true });
  }
});

test("an additive field type is checked against the provider's marker", async () => {
  const workspace = temporaryDirectory();
  try {
    const built = await buildCase("02-additive-field", workspace);
    assert.equal(runTsc(built.directory, true).status, 0);
    rmSync(join(workspace, "node_modules"), { recursive: true, force: true });
    const mismatched = await buildCase(
      "02-additive-field",
      temporaryDirectory(),
      "rcMarker_0000000000000000",
    );
    const compiled = runTsc(mismatched.directory, true);
    assert.notEqual(compiled.status, 0);
    assert.match(compiled.output, /rcMarker_/);
  } finally {
    rmSync(workspace, { recursive: true, force: true });
  }
});
