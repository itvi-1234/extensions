import { readFileSync } from "node:fs";
import * as prettier from "prettier";
import ts from "typescript";
import { stringify } from "yaml";

import { fail } from "./diagnostics.js";
import type { Model } from "./model.js";
import type { EmissionPlan, TypeExpr } from "./plan.js";
import type { PackageDependency } from "./target.js";
import { fillJson, fillText, readTemplate } from "./templates.js";

const EMITTER_PACKAGE = JSON.parse(
  readFileSync(new URL("../../package.json", import.meta.url), "utf-8"),
) as { version: string; bin: Record<string, string> };

export const EMITTER_NAME: string = Object.keys(EMITTER_PACKAGE.bin)[0]!;
export const EMITTER_VERSION: string = EMITTER_PACKAGE.version;
export const TYPESCRIPT_VERSION: string = ts.version;
export const PRETTIER_VERSION: string = prettier.version;

export function header(model: Model): string {
  return `Code generated by ${EMITTER_NAME} ${EMITTER_VERSION} from model ${model["metadata"].semanticSha256}; DO NOT EDIT.`;
}

function dependencyRange(dependency: PackageDependency): string {
  return dependency.versionRange ?? `^${dependency.version}`;
}

function packageJson(plan: EmissionPlan, model: Model): string {
  const { target } = plan;
  const names = target.dependencies.map((item) => item.packageName);
  if (new Set(names).size !== names.length) {
    fail(
      "package-config",
      "RCT1006",
      target.packageKey,
      "multiple direct extensions use the same npm package name",
      "/dependencies",
    );
  }
  const dependencies = Object.fromEntries(
    [...target.dependencies]
      .sort((a, b) => (a.packageName < b.packageName ? -1 : 1))
      .map((item) => [item.packageName, dependencyRange(item)]),
  );
  const repository = target.repositoryUrl.endsWith(".git")
    ? target.repositoryUrl
    : `${target.repositoryUrl}.git`;
  const template = "package.json.tmpl";
  const filled = fillJson(template, JSON.parse(readTemplate(template)), {
    header: header(model),
    name: target.packageName,
    version: target.version,
    minimumNodeVersion: target.minimumNodeVersion,
    repositoryUrl: repository,
    sourceDirectory: target.sourceDirectory,
    dependencies,
    typescriptVersion: TYPESCRIPT_VERSION,
  });
  return JSON.stringify(filled, null, 2) + "\n";
}

function tsconfig(model: Model): string {
  const template = "tsconfig.json.tmpl";
  return fillText(template, readTemplate(template), { header: header(model) });
}

function modelLocation(item: any): string {
  return item.provenance.coordinate + (item.provenance.jsonPointer ?? "");
}

function modelRef(provenance: any): Record<string, string> {
  const result: Record<string, string> = { coordinate: provenance.coordinate };
  if (provenance.jsonPointer) result["jsonPointer"] = provenance.jsonPointer;
  return result;
}

function modelLocations(model: Model): [Map<string, any>, Map<string, any>] {
  const provenances = new Map<string, any>();
  const shapes = new Map<string, any>();
  const add = (item: any): void => {
    const provenance = item.provenance;
    const place = modelLocation(item);
    const previous = provenances.get(place);
    if (previous !== undefined && JSON.stringify(previous) !== JSON.stringify(provenance)) {
      fail(
        "model",
        "RCT1012",
        place,
        "ambiguous legacy plan coordinate; separate model coordinate and JSON Pointer are required",
      );
    }
    provenances.set(place, provenance);
  };
  const walk = (shape: any): void => {
    add(shape);
    if (!shapes.has(modelLocation(shape))) shapes.set(modelLocation(shape), shape);
    for (const property of shape.properties ?? []) {
      add(property);
      walk(property.shape);
    }
    for (const child of [shape.items, shape.mapValues]) if (child !== undefined) walk(child);
    for (const child of shape.variants ?? []) walk(child);
  };
  const vocabulary = model["vocabulary"];
  for (const group of [
    "ownedDeclarations",
    "importedDeclarations",
    "interfaces",
    "conditionFields",
    "valueDomains",
  ]) {
    for (const item of vocabulary[group] ?? []) add(item);
  }
  for (const scope of model["scopes"] ?? []) if (scope.projection) walk(scope.projection);
  for (const schema of model["schemas"] ?? []) {
    add(schema);
    walk(schema.projection);
    for (const definition of schema.definitions ?? []) {
      add(definition);
      walk(definition.shape);
    }
  }
  return [provenances, shapes];
}

const BUILTINS: Record<string, string> = {
  string: "string",
  boolean: "boolean",
  integer: "number",
  number: "number",
  null: "null",
  any: "JSONValue",
};

function reference(expression: TypeExpr, plan: EmissionPlan): Record<string, string> {
  if (["object", "enum", "ref", "alias"].includes(expression.kind)) {
    return { type: plan.names.get(expression.symbolKey)! };
  }
  return { builtin: BUILTINS[expression.kind]! };
}

function structuralTypes(
  plan: EmissionPlan,
  provenances: Map<string, any>,
  shapes: Map<string, any>,
): any[] {
  const contracts = new Map<string, string>();
  for (const item of [...plan.declarations, ...plan.importedDeclarations])
    contracts.set(item.method, item.coordinate);
  const result: any[] = [];
  for (const item of plan.types) {
    const shape = shapes.get(item.coordinate);
    const aliasKind = item.expression?.kind ?? "";
    const construct =
      item.kind === "object" && shape.kind !== "object"
        ? "wrapper"
        : item.kind === "object"
          ? "object"
          : item.kind === "enum"
            ? "scalar"
            : ({ array: "collection", map: "map", union: "union" } as Record<string, string>)[
                aliasKind
              ]!;
    const entry: Record<string, any> = {
      modelRef: modelRef(provenances.get(item.coordinate)),
      sourceName: item.sourceName,
      nativeName: item.name,
      construct,
      file: "bindings.ts",
    };
    if (item.kind === "enum") {
      entry["underlying"] = "string";
      entry["members"] = item.members.map(([native, value]) => ({
        modelRef: modelRef(provenances.get(item.coordinate)),
        nativeName: native,
        value,
      }));
    }
    if (item.kind === "object") {
      entry["fields"] = item.fields.map((field) => ({
        modelRef: modelRef(provenances.get(field.coordinate)),
        sourceName: construct === "wrapper" ? item.sourceName : field.sourceName,
        nativeName: field.name,
        required: field.required,
        value: reference(field.typeExpr, plan),
        ...(construct === "wrapper" ? { synthetic: true } : {}),
      }));
      if (item.marker !== null) {
        entry["implements"] = [
          {
            declarationCoordinate: contracts.get(item.marker.method)!,
            markerMethod: item.marker.method,
          },
        ];
      }
    }
    if (item.kind === "alias") {
      if (construct === "collection" || construct === "map") {
        const child = shape[construct === "collection" ? "items" : "mapValues"];
        entry["element"] = {
          modelRef: modelRef(child.provenance),
          value: reference(item.expression!.arguments[0]!, plan),
        };
      } else {
        entry["variants"] = shape.variants.map((child: any, index: number) => ({
          modelRef: modelRef(child.provenance),
          value: reference(item.expression!.arguments[index]!, plan),
        }));
      }
    }
    result.push(entry);
  }
  return result.sort((a, b) =>
    a.nativeName < b.nativeName ? -1 : a.nativeName > b.nativeName ? 1 : 0,
  );
}

function manifest(plan: EmissionPlan, model: Model): string {
  const [provenances, shapes] = modelLocations(model);
  const rootId: string = model["rootExtension"].id;
  const declarations = new Map<string, any>();
  for (const group of ["ownedDeclarations", "importedDeclarations"]) {
    for (const item of model["vocabulary"][group] ?? []) declarations.set(item.kind, item);
  }
  const fields = new Map<string, any>();
  for (const item of model["vocabulary"].conditionFields ?? []) {
    if (item.owner === rootId)
      fields.set(JSON.stringify([item.kind, item.interfaceType ?? "", item.path]), item);
  }
  const rootBindings: any[] = [];
  for (const schema of model["schemas"] ?? []) {
    if (schema.owner !== rootId) continue;
    const kind: string = schema.kind ?? schema.id;
    if (!declarations.has(kind)) continue;
    const interfaceType: string = schema.interfaceType ?? "";
    for (const property of schema.projection.properties ?? []) {
      const name: string = property.name;
      const sourceName = name === "interface" && interfaceType ? interfaceType : name;
      const nativeName = plan.names.get(`type:field:${schema.coordinate}:${name}`);
      if (nativeName === undefined) {
        fail(
          "model",
          "RCT1012",
          schema.coordinate,
          `root property '${name}' has no declaration field type`,
        );
      }
      const vocabularyField = fields.get(JSON.stringify([kind, interfaceType, name]));
      const role =
        name === "interface" && interfaceType
          ? "interface"
          : vocabularyField !== undefined
            ? "condition-field"
            : "schema-field";
      const binding: Record<string, any> = {
        role,
        modelRef: modelRef(property.provenance),
        declarationCoordinate: declarations.get(kind).coordinate,
        scope: { kind, ...(interfaceType ? { interfaceType } : {}) },
        sourceName,
        path: [{ name }],
        value: { type: nativeName },
        schemaCoordinate: schema.coordinate,
      };
      if (role === "interface") binding["fixedInterfaceType"] = interfaceType;
      if (vocabularyField !== undefined)
        binding["vocabularyCoordinate"] = vocabularyField.coordinate;
      rootBindings.push(binding);
    }
  }
  const text = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
  const document = {
    apiVersion: "runtimeconditions.io/bindings/v1alpha2",
    kind: "RuntimeConditionsBindingManifest",
    generated: {
      nonEditable: true,
      emitter: `${EMITTER_NAME}@sha256:${plan.target.emitterSha256}`,
      version: EMITTER_VERSION,
    },
    model: { apiVersion: model["apiVersion"], semanticSha256: plan.modelDigest },
    extension: { id: rootId, semanticSha256: model["rootExtension"].semanticSha256 },
    package: {
      language: "typescript",
      coordinate: plan.target.packageName,
      name: plan.target.packageName,
      version: plan.target.version,
      minimumNodeVersion: plan.target.minimumNodeVersion,
    },
    declarations: plan.declarations.map((item) => ({
      modelRef: modelRef(provenances.get(item.coordinate)),
      owner: rootId,
      sourceName: item.kind,
      function: item.function,
      markerInterface: item.protocol,
      markerMethod: item.method,
      file: "bindings.ts",
    })),
    importedMarkerContracts: plan.importedDeclarations.map((item) => ({
      modelRef: modelRef(provenances.get(item.coordinate)),
      owner: item.owner,
      sourceName: item.kind,
      markerInterface: item.protocol,
      markerMethod: item.method,
      providerPackage: item.providerPackage,
    })),
    rootBindings: rootBindings.sort(
      (a, b) =>
        text(a.declarationCoordinate, b.declarationCoordinate) ||
        text(a.modelRef.coordinate, b.modelRef.coordinate) ||
        text(a.modelRef.jsonPointer ?? "", b.modelRef.jsonPointer ?? ""),
    ),
    types: structuralTypes(plan, provenances, shapes),
  };
  return `# ${header(model)}\n${stringify(document, { lineWidth: 0, indent: 2 })}`;
}

export function renderResources(plan: EmissionPlan, model: Model): Record<string, string> {
  if (plan.target.emitterSha256 === "") {
    fail(
      "package-config",
      "RCT1006",
      plan.target.packageKey,
      "emitterSha256 is required when emitting package resources",
      "/emitterSha256",
    );
  }
  if (
    model["metadata"].semanticSha256 !== plan.modelDigest ||
    model["rootExtension"].id !== plan.target.rootExtension
  ) {
    fail("model", "RCT1003", "model", "emission plan does not match supplied model");
  }
  const root = model["rootExtension"];
  const roots = model["extensions"].filter((item: any) => item.id === root.id);
  if (roots.length !== 1 || roots[0].semanticSha256 !== root.semanticSha256) {
    fail(
      "model",
      "RCT1003",
      root.id,
      "root extension digest does not match model extension closure",
    );
  }
  return {
    "package.json": packageJson(plan, model),
    "tsconfig.json": tsconfig(model),
    "runtimeconditions/runtimeconditions.bindings.yaml": manifest(plan, model),
  };
}
